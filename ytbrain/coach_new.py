def skills(s: Spec) -> dict[str, str]:
    lines = []
    for i, (n, d) in enumerate(s.fields):
        first = " When no Project is active (`project` is null), or this is another @noun@, call `coach_project` with action `create` and its name as soon as you have it, so everything after is saved to that Project." if i == 0 else ""
        lines.append(f"   - {d} (`{n}`).{first}")
    setup = SETUP.replace("@interview@", "\n".join(lines))
    return {n: _fill(t, s) for n, t in (("ask", ASK), ("coach", COACH), ("setup", setup))}


def create(root: Path, spec: Spec, like: str | None = None, known_domains=None) -> dict:
    """Write the Pack and its skills under `root`, load it back, and return what was done. Nothing is left behind if
    the written Pack doesn't load."""
    validate(spec, root)
    pdir = root / "packs" / spec.id
    written: list[Path] = []
    try:
        pdir.mkdir(parents=True)
        (pdir / "pack.toml").write_text(pack_toml(spec), encoding="utf-8")
        written.append(pdir / "pack.toml")
        for name, text in skills(spec).items():
            f = pdir / "skills" / name / "SKILL.md"
            f.parent.mkdir(parents=True)
            f.write_text(text, encoding="utf-8")
            written.append(f)
        copied = copy_cases(root, like, spec.id) if like else []
        pack = PK.load(spec.id, root=root, check_skills=False)
        if gone := [s for s in pack.skills if not pack.skill_file(s, root).exists()]:
            raise NewCoachError(f"the shared skill(s) {', '.join(gone)} are missing from plugin/skills/")
    except Exception:
        shutil.rmtree(pdir, ignore_errors=True)
        if like:
            shutil.rmtree(root / "ytbrain" / "eval" / "coach_cases" / spec.id, ignore_errors=True)
        raise
    missing = [d for d in spec.domains if known_domains is not None and d not in set(known_domains)]
    return {"pack": pdir / "pack.toml", "files": written, "cases": copied, "missing_domains": missing}


def copy_cases(root: Path, like: str, new_id: str) -> list[Path]:
    """Copy an example coach's evaluation cases as a starting point (steps G4-G8 read coach_cases/<id>/). They are
    written about the example's subject: rewrite the scenarios before you rely on a gate."""
    base = root / "ytbrain" / "eval" / "coach_cases"
    src = base if like == PK.DEFAULT_PACK else base / like
    if not (root / "packs" / like / "pack.toml").exists():
        raise NewCoachError(f"--like {like!r}: no such Pack (have: {', '.join(PK.all_ids(root))})")
    dst = base / new_id
    out = []
    for n in CASE_FILES:
        f = src / f"{n}.jsonl"
        if f.exists():
            dst.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(f, dst / f.name)
            out.append(dst / f.name)
    return out


def parse_field(text: str) -> tuple[str, str]:
    """`name=description` from the command line."""
    name, sep, desc = text.partition("=")
    name, desc = name.strip(), desc.strip()
    if not sep or not name or not desc:
        raise NewCoachError(f"--field {text!r}: write it as name=description (e.g. system=\"the system, in one line\")")
    return name, desc


def split(v: str | None) -> tuple[str, ...]:
    return tuple(x.strip() for x in re.split(r"[,\s]+", v or "") if x.strip())
