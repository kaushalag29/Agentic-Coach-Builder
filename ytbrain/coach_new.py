"""`ytbrain coach new <id>`: draft a new coach (a Pack) from a short description (docs/build-your-own-coach.md).

It writes what steps 3 and 4 of that guide ask you to write by hand: `packs/<id>/pack.toml` (identity, words,
Domains, memory modules, profile fields, the coaching contract) and the three skills a coach needs in its own
words (`ask`, `coach`, `setup`). The shared skills (`project`, `status`, `export`, `forget`, `feedback`) are used
as they are. Nothing is generated by a model: the text comes from templates, so the result is the same every run
and every line is yours to edit. It never overwrites a Pack, never touches the Library, and never edits
`domains.yaml`: a Domain that doesn't exist yet is reported with the exact command that declares it.

Standard library only (like `ytbrain.packs`); the generated Pack is loaded back with `packs.load` before the
command reports success, so what it writes always passes the loader.
"""
